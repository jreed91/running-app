import Foundation
import SwiftData

@Model
final class ScheduledWorkout {
    #Index<ScheduledWorkout>([\.id], [\.scheduledDate], [\.isCompleted])

    var id: UUID = UUID()
    var scheduledDate: Date = Date()
    var workoutType: WorkoutType = WorkoutType.easy
    var targetDistanceMeters: Double?
    /// Lower bound of target pace range in seconds/km.
    var targetPaceLowerBound: Double?
    /// Upper bound of target pace range in seconds/km.
    var targetPaceUpperBound: Double?
    var isCompleted: Bool = false
    var notes: String?

    /// Local tracking ID assigned when this workout is synced via ``HealthKitRepository``.
    var healthKitPlanID: String?

    /// JSON-encoded `[WorkoutInterval]` — only set for interval sessions.
    var intervalsData: Data?

    /// JSON-encoded ``WorkoutStructure`` — set for structured workouts generated by
    /// ``TrainingPlanService/adaptWorkout(scheduled:history:profile:)``.
    var structureData: Data?

    var week: TrainingWeek?

    @Relationship(deleteRule: .nullify, inverse: \RunWorkout.scheduledWorkout)
    var completedWorkout: RunWorkout?

    // MARK: Computed helpers

    var intervals: [WorkoutInterval] {
        get { intervalsData?.decode([WorkoutInterval].self) ?? [] }
        set { intervalsData = .encoded(newValue) }
    }

    var targetPaceRange: ClosedRange<Double>? {
        guard let lo = targetPaceLowerBound, let hi = targetPaceUpperBound, lo <= hi else { return nil }
        return lo...hi
    }

    var workoutStructure: WorkoutStructure? {
        get { structureData?.decode(WorkoutStructure.self) }
        set { structureData = newValue.flatMap { Data.encoded($0) } }
    }

    init(
        scheduledDate: Date,
        workoutType: WorkoutType,
        targetDistanceMeters: Double? = nil,
        targetPaceLowerBound: Double? = nil,
        targetPaceUpperBound: Double? = nil,
        notes: String? = nil
    ) {
        self.id = UUID()
        self.scheduledDate = scheduledDate
        self.workoutType = workoutType
        self.targetDistanceMeters = targetDistanceMeters
        self.targetPaceLowerBound = targetPaceLowerBound
        self.targetPaceUpperBound = targetPaceUpperBound
        self.notes = notes
        self.isCompleted = false
    }
}
