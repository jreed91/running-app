import Foundation
import SwiftData

@Model
final class ScheduledWorkout {
    #Index<ScheduledWorkout>([\.id], [\.scheduledDate], [\.isCompleted])

    var id: UUID = UUID()
    var scheduledDate: Date = Date()
    /// Raw-backed storage for `workoutType` to keep CloudKit fields primitive.
    var workoutTypeRaw: String = WorkoutType.easy.rawValue
    /// Raw-backed storage for `workoutLocation` to keep CloudKit fields primitive.
    var workoutLocationRaw: String = WorkoutLocation.outdoor.rawValue
    /// Absorbs the old CloudKit `workoutType` field so migration can recover it.
    @Attribute(originalName: "workoutType")
    var workoutTypeLegacy: String? = nil
    /// Absorbs the old CloudKit `workoutLocation` field so migration can recover it.
    @Attribute(originalName: "workoutLocation")
    var workoutLocationLegacy: String? = nil
    var targetDistanceMeters: Double?
    /// Lower bound of target pace range in seconds/km.
    var targetPaceLowerBound: Double?
    /// Upper bound of target pace range in seconds/km.
    var targetPaceUpperBound: Double?
    var isCompleted: Bool = false
    var notes: String?

    /// Local tracking ID assigned when this workout is synced via ``HealthKitRepository``.
    var healthKitPlanID: String?

    /// JSON-encoded `[WorkoutInterval]` — only set for interval sessions.
    var intervalsData: Data?

    /// JSON-encoded ``WorkoutStructure`` — set for structured workouts generated by
    /// ``TrainingPlanService/adaptWorkout(scheduled:history:profile:)``.
    var structureData: Data?

    /// JSON-encoded ``StrengthWorkoutPlan`` — set for `.strength` workouts.
    var strengthData: Data?

    /// The name of the runner's own workout swapped onto this day ("6 × 800 m"), shown in
    /// place of the session type (Custom workouts, PR 4). Cleared when the coach rewrites
    /// the session, since the structure is then no longer the one the name describes.
    var customWorkoutName: String?

    var week: TrainingWeek?

    @Relationship(deleteRule: .nullify, inverse: \RunWorkout.scheduledWorkout)
    var completedWorkout: RunWorkout?

    /// Primitive backup of the linked run workout's ID. See ``RunWorkout/linkedScheduledWorkoutID``
    /// for rationale.
    var linkedRunWorkoutID: UUID?

    @Relationship(deleteRule: .nullify, inverse: \StrengthWorkout.scheduledWorkout)
    var completedStrengthWorkout: StrengthWorkout?

    /// Primitive backup of the linked strength workout's ID for CloudKit relationship repair.
    var linkedStrengthWorkoutID: UUID?

    // MARK: Computed helpers

    var intervals: [WorkoutInterval] {
        get { intervalsData?.decode([WorkoutInterval].self) ?? [] }
        set { intervalsData = .encoded(newValue, keeping: intervalsData) }
    }

    /// What the plan, the widgets and the Watch call the session: the custom workout's
    /// name when one was swapped in, else the session type ("Intervals").
    var displayTitle: String {
        if let name = customWorkoutName?.trimmingCharacters(in: .whitespacesAndNewlines), !name.isEmpty {
            return name
        }
        return workoutType.localizedName
    }

    var targetPaceRange: ClosedRange<Double>? {
        guard let lo = targetPaceLowerBound, let hi = targetPaceUpperBound, lo <= hi else { return nil }
        return lo...hi
    }

    var workoutStructure: WorkoutStructure? {
        get { structureData?.decode(WorkoutStructure.self) }
        set { structureData = newValue.flatMap { Data.encoded($0, keeping: structureData) } }
    }

    var strengthPlan: StrengthWorkoutPlan? {
        get { strengthData?.decode(StrengthWorkoutPlan.self) }
        set { strengthData = newValue.flatMap { Data.encoded($0, keeping: strengthData) } }
    }

    var workoutType: WorkoutType {
        get { WorkoutType(rawValue: workoutTypeRaw) ?? .easy }
        set { workoutTypeRaw = newValue.rawValue }
    }

    var workoutLocation: WorkoutLocation {
        get { WorkoutLocation(rawValue: workoutLocationRaw) ?? .outdoor }
        set { workoutLocationRaw = newValue.rawValue }
    }

    init(
        scheduledDate: Date,
        workoutType: WorkoutType,
        targetDistanceMeters: Double? = nil,
        targetPaceLowerBound: Double? = nil,
        targetPaceUpperBound: Double? = nil,
        notes: String? = nil
    ) {
        self.id = UUID()
        self.scheduledDate = scheduledDate
        self.workoutType = workoutType
        self.targetDistanceMeters = targetDistanceMeters
        self.targetPaceLowerBound = targetPaceLowerBound
        self.targetPaceUpperBound = targetPaceUpperBound
        self.notes = notes
        self.isCompleted = false
    }
}

// MARK: - Adaptation

extension ScheduledWorkout {

    /// Copies an AI-adapted session's prescription onto this persisted workout.
    ///
    /// The coach returns an **unmanaged** `ScheduledWorkout` describing what to run.
    /// It is never inserted or related to a week — doing that auto-inserts it and leaves
    /// a phantom duplicate in the plan — so the adaptation is applied field by field to
    /// the row that already exists.
    ///
    /// Which fields those are was written out twice, in `PlanTabView`'s Smart Adapt loop
    /// and in `RunSummaryView`'s apply-coach-feedback path (D1/D7). Two hand-maintained
    /// copies of an eight-field assignment is a field-drops-off-one-of-them bug waiting
    /// to happen, and the field most likely to be forgotten is the last one:
    /// `healthKitPlanID` is cleared because the workout now on the Watch describes the
    /// *old* prescription, so it has to be re-synced rather than matched.
    ///
    /// Identity, scheduling, and completion state are deliberately untouched: the coach
    /// changes what the session is, never when it is or whether it happened.
    ///
    /// The session is also noted in ``AdaptedSessions``, so the next run's automatic pace
    /// refresh leaves the coach's answer alone for a week instead of overwriting it (P1.1).
    func applyAdaptation(from adapted: ScheduledWorkout) {
        workoutType = adapted.workoutType
        workoutStructure = adapted.workoutStructure
        targetDistanceMeters = adapted.targetDistanceMeters
        targetPaceLowerBound = adapted.targetPaceLowerBound
        targetPaceUpperBound = adapted.targetPaceUpperBound
        notes = adapted.notes
        intervals = adapted.intervals
        customWorkoutName = nil
        healthKitPlanID = nil
        AdaptedSessions.record(id)
    }

    /// Puts one of the runner's own workouts on this day in place of what the plan had
    /// (Custom workouts, PR 4).
    ///
    /// The day, its place in the week and its completion state stay; what is run changes.
    /// The plan's pace band goes, because the reps carry their own paces, and so does the
    /// coach's note, which described the old session. `healthKitPlanID` is cleared so the
    /// Workout app copy is rebuilt from the new structure on the next sync, and the day is
    /// noted in ``AdaptedSessions`` so the next run's automatic pace refresh leaves the
    /// runner's choice alone, as it does the coach's.
    func applyCustomWorkout(name: String, structure: WorkoutStructure, notes: String?) {
        workoutType = .interval
        workoutStructure = structure
        intervals = []
        targetDistanceMeters = structure.totalEstimatedDistanceMeters > 0 ? structure.totalEstimatedDistanceMeters : nil
        targetPaceLowerBound = nil
        targetPaceUpperBound = nil
        self.notes = notes.flatMap { $0.isEmpty ? nil : $0 }
        customWorkoutName = name
        healthKitPlanID = nil
        AdaptedSessions.record(id)
    }
}
